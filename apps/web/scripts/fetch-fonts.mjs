/**
 * Self-hosts the variant typefaces as woff2 and writes src/styles/fonts.css.
 * Run: npm run fonts -w @hvac/web
 */
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0 Safari/537.36'

const here = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(here, '..')
const fontDir = path.join(webRoot, 'public', 'fonts')
const cssOut = path.join(webRoot, 'src', 'styles', 'fonts.css')

const SOURCES = [
  {
    key: 'clash-display',
    url: 'https://api.fontshare.com/v2/css?f%5B%5D=clash-display@500,600&display=swap',
  },
  { key: 'satoshi', url: 'https://api.fontshare.com/v2/css?f%5B%5D=satoshi@400,500,700&display=swap' },
  {
    key: 'instrument-serif',
    url: 'https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&display=swap',
  },
  { key: 'hanken-grotesk', url: 'https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@400;500;700&display=swap' },
  { key: 'jetbrains-mono', url: 'https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;500&display=swap' },
  { key: 'ibm-plex-mono', url: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&display=swap' },
]

const LATIN_HINT = 'U+0000-00FF'

function field(block, name) {
  const match = block.match(new RegExp(`${name}:\\s*([^;]+);`, 'i'))
  return match ? match[1].trim() : ''
}

function srcUrl(block) {
  const matches = [...block.matchAll(/url\(([^)]+)\)/g)]
  const urls = matches
    .map((m) => m[1].replace(/['"]/g, '').trim())
    // Fontshare returns protocol-relative URLs (`//cdn.fontshare.com/...`).
    .map((url) => (url.startsWith('//') ? `https:${url}` : url))
  return urls.find((u) => u.endsWith('.woff2')) ?? urls[0] ?? ''
}

async function run() {
  await mkdir(fontDir, { recursive: true })
  const faces = []
  let downloaded = 0

  for (const source of SOURCES) {
    const res = await fetch(source.url, { headers: { 'User-Agent': UA } })
    if (!res.ok) {
      console.warn(`! ${source.key}: HTTP ${res.status}`)
      continue
    }
    const css = await res.text()
    const blocks = css.split('@font-face').slice(1).map((chunk) => chunk.slice(0, chunk.indexOf('}') + 1))

    for (const block of blocks) {
      const family = field(block, 'font-family').replace(/['"]/g, '')
      const weight = field(block, 'font-weight') || '400'
      const style = field(block, 'font-style') || 'normal'
      const range = field(block, 'unicode-range')
      const remote = srcUrl(block)
      if (!family || !remote) continue
      // Keep the basic-latin face only; the rest would triple the payload.
      if (range && !range.includes(LATIN_HINT) && !range.includes('U+0020')) continue

      const ext = remote.endsWith('.woff2') ? 'woff2' : 'woff'
      const file = `${source.key}-${weight}${style.includes('italic') ? '-italic' : ''}.${ext}`
      const binary = await fetch(remote, { headers: { 'User-Agent': UA } })
      if (!binary.ok) {
        console.warn(`! ${file}: HTTP ${binary.status}`)
        continue
      }
      await writeFile(path.join(fontDir, file), Buffer.from(await binary.arrayBuffer()))
      downloaded += 1

      faces.push(
        [
          '@font-face {',
          `  font-family: '${family}';`,
          `  src: url('/fonts/${file}') format('${ext === 'woff2' ? 'woff2' : 'woff'}');`,
          `  font-weight: ${weight};`,
          `  font-style: ${style};`,
          '  font-display: swap;',
          range ? `  unicode-range: ${range};` : null,
          '}',
        ]
          .filter(Boolean)
          .join('\n'),
      )
    }
  }

  const header = `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n\n`
  await writeFile(cssOut, header + faces.join('\n\n') + '\n')
  console.log(`[fonts] ${downloaded} files -> public/fonts, ${faces.length} faces -> src/styles/fonts.css`)
}

run().catch((error) => {
  console.error('[fonts] failed:', error)
  process.exitCode = 1
})
